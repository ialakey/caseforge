import { z } from 'zod';

/**
 * The analytics contour.
 *
 * The split that matters, and the reason this module is small: **the database
 * is already the analytics store for everything that moved money.** Openings,
 * deposits, battles, referrals and withdrawals are rows with amounts and
 * timestamps, and a report over them is a query. Re-emitting them as events
 * would create a second set of numbers that can disagree with the ledger, and
 * when a report and the ledger disagree the report is the one nobody trusts
 * again.
 *
 * So the event stream carries only what the database cannot answer: who arrived,
 * where from, what they looked at, and where they stopped. Everything else is
 * computed from the tables that already exist, and the two meet in the funnel —
 * an event-based top, a ledger-based bottom.
 */

/** Events the browser is allowed to report. */
export const AnalyticsEventType = {
  PAGE_VIEW: 'page_view',
  /** The Steam button was pressed — the last step before we lose the visitor to the redirect. */
  SIGN_IN_STARTED: 'sign_in_started',
  /** The top-up dialog was opened, which is not the same as topping up. */
  DEPOSIT_OPENED: 'deposit_opened',
  /** A promo code was typed into it. */
  PROMO_TRIED: 'promo_tried',
  /** A battle was created or joined from the lobby — the click, not the settled battle. */
  BATTLE_INTENT: 'battle_intent',
  /** An invite link was followed. */
  REFERRAL_VISIT: 'referral_visit',
} as const;
export type AnalyticsEventType = (typeof AnalyticsEventType)[keyof typeof AnalyticsEventType];

export const ANALYTICS_EVENT_TYPES = Object.values(AnalyticsEventType);

/** How many events one request may carry. The client batches on a short timer. */
export const ANALYTICS_BATCH_MAX = 20;

/**
 * One reported event.
 *
 * `anonId` is not in the payload: the client sends it once per batch, because a
 * batch comes from one browser by definition and repeating it per event is only
 * a way for the two to disagree.
 */
export const analyticsEventSchema = z.object({
  type: z.enum(ANALYTICS_EVENT_TYPES as [string, ...string[]]),
  /** Same-origin path only; a full URL would let a caller write anything into reports. */
  path: z.string().trim().max(512).optional(),
  referrer: z.string().trim().max(512).optional(),
  utmSource: z.string().trim().max(120).optional(),
  utmMedium: z.string().trim().max(120).optional(),
  utmCampaign: z.string().trim().max(120).optional(),
  /** A small bag of extra detail. Capped so a report cannot be filled with prose. */
  meta: z.record(z.string(), z.union([z.string().max(200), z.number(), z.boolean()])).optional(),
});
export type AnalyticsEventInput = z.infer<typeof analyticsEventSchema>;

export const analyticsCollectSchema = z.object({
  /**
   * Stable per browser, generated by the client. It is not an identity: it
   * exists so "visitors" is not the same number as "page views", and it is
   * replaced whenever the browser forgets it.
   */
  anonId: z.string().trim().min(8).max(64),
  /** Resets after a gap of inactivity, so sessions are countable. */
  sessionId: z.string().trim().min(8).max(64),
  events: z.array(analyticsEventSchema).min(1).max(ANALYTICS_BATCH_MAX),
});
export type AnalyticsCollectInput = z.infer<typeof analyticsCollectSchema>;

/** How long a browser may be idle before its next event starts a new session. */
export const SESSION_IDLE_MS = 30 * 60 * 1000;

