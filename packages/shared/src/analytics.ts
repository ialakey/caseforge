export interface TimeSeriesPoint {
  /** `YYYY-MM-DD`, in UTC — the same day boundary the rollup uses. */
  date: string;
  value: number;
}

/** A day key, UTC. Reports must not move when the operator travels. */
export function dayKey(date: Date): string {
  return date.toISOString().slice(0, 10);
}

export function addDays(date: Date, days: number): Date {
  const next = new Date(date);
  next.setUTCDate(next.getUTCDate() + days);
  return next;
}

/**
 * Every day between two dates, inclusive.
 *
 * A series with missing days is drawn as a straight line across them, which is
 * a lie: no data is not the same as no change. The gaps are filled with zeros
 * here so every chart in the panel agrees about that.
 */
export function fillSeries(
  rows: readonly TimeSeriesPoint[],
  from: Date,
  to: Date,
): TimeSeriesPoint[] {
  const byDate = new Map(rows.map((row) => [row.date, row.value]));
  const series: TimeSeriesPoint[] = [];
  for (let cursor = new Date(dayKey(from)); cursor <= to; cursor = addDays(cursor, 1)) {
    const key = dayKey(cursor);
    series.push({ date: key, value: byDate.get(key) ?? 0 });
  }
  return series;
}

/** A share, with the division by zero that reports are full of handled once. */
export function share(part: number, whole: number): number {
  return whole > 0 ? part / whole : 0;
}

export interface FunnelStepInput {
  key: string;
  count: number;
}

export interface FunnelStep extends FunnelStepInput {
  /** Share of the first step. */
  ofFirst: number;
  /** Share of the step before it — where the drop-off actually is. */
  ofPrevious: number;
}

/**
 * The funnel, with both conversions.
 *
 * Two numbers rather than one because they answer different questions: share
 * of the top says how much of the traffic ends up playing, share of the
 * previous step says which step is losing them. A funnel with only the first is
 * a funnel where every step after a bad one looks bad.
 */
export function funnel(steps: readonly FunnelStepInput[]): FunnelStep[] {
  const first = steps[0]?.count ?? 0;
  return steps.map((step, index) => ({
    ...step,
    // The first step is the reference, so it is all of itself by definition —
    // including on a day with no traffic at all, where a share computed from
    // the count would render the top of the funnel as 0% and read as a bug.
    ofFirst: index === 0 ? 1 : share(step.count, first),
    ofPrevious: index === 0 ? 1 : share(step.count, steps[index - 1]!.count),
  }));
}

export interface RetentionRow {
  /** The week the players signed up in, as the Monday of that week. */
  cohort: string;
  size: number;
  /** Share of the cohort still playing in week 0, 1, 2 … */
  weeks: number[];
}

/** The Monday of a date's week, UTC. */
export function weekKey(date: Date): string {
  const monday = new Date(dayKey(date));
  // getUTCDay: 0 is Sunday, which is the end of the week here, not the start.
  const offset = (monday.getUTCDay() + 6) % 7;
  return dayKey(addDays(monday, -offset));
}

/**
 * Turns sign-up and activity dates into a cohort grid.
 *
 * Pure so the shape of the table is testable: an off-by-one in a retention
 * matrix is invisible on screen and changes every conclusion drawn from it.
 */
export function retention(
  players: ReadonlyArray<{ signedUpAt: Date; activeAt: readonly Date[] }>,
  weeksWide: number,
): RetentionRow[] {
  const cohorts = new Map<string, { size: number; weeks: number[] }>();

  for (const player of players) {
    const cohort = weekKey(player.signedUpAt);
    const row = cohorts.get(cohort) ?? { size: 0, weeks: new Array(weeksWide).fill(0) };
    row.size += 1;

    // A player counts once per week however often they played in it.
    const seen = new Set<number>();
    for (const active of player.activeAt) {
      const offset = Math.floor(
        (new Date(weekKey(active)).getTime() - new Date(cohort).getTime()) / (7 * 86_400_000),
      );
      if (offset >= 0 && offset < weeksWide) seen.add(offset);
    }
    for (const offset of seen) row.weeks[offset] += 1;

    cohorts.set(cohort, row);
  }

  return [...cohorts.entries()]
    .sort((a, b) => (a[0] < b[0] ? 1 : -1))
    .map(([cohort, row]) => ({
      cohort,
      size: row.size,
      weeks: row.weeks.map((count) => share(count, row.size)),
    }));
}

/**
 * An axis maximum a human would have chosen.
 *
 * A chart whose axis tops out at 731 is a chart nobody can read a value off.
 * Rounded up to 1, 2 or 5 times a power of ten.
 */
export function niceMax(values: readonly number[]): number {
  const peak = Math.max(0, ...values);
  if (peak === 0) return 1;
  const magnitude = 10 ** Math.floor(Math.log10(peak));
  for (const step of [1, 2, 2.5, 5, 10]) {
    if (peak <= step * magnitude) return step * magnitude;
  }
  return 10 * magnitude;
}

/**
 * The polyline for a series, in SVG user units.
 *
 * The geometry is here rather than in the chart component because it is
 * arithmetic, and arithmetic in a component is arithmetic nobody tests. The
 * component keeps the axes, the labels and the colours.
 */
export function seriesPath(
  values: readonly number[],
  width: number,
  height: number,
  max = niceMax(values),
): string {
  if (values.length === 0) return '';
  if (values.length === 1) {
    const y = height - (values[0]! / max) * height;
    return `M 0 ${round(y)} L ${width} ${round(y)}`;
  }
  const step = width / (values.length - 1);
  return values
    .map((value, index) => {
      const x = round(index * step);
      const y = round(height - (value / max) * height);
      return `${index === 0 ? 'M' : 'L'} ${x} ${y}`;
    })
    .join(' ');
}

function round(value: number): number {
  return Math.round(value * 100) / 100;
}

